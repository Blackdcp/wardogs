function sourceSignature(item: WardogsItem): number {
  const source = JSON.stringify([item.name, item.type, item.subtype, ...proseFields.map((field) => item[field])]);
  let hash = 2166136261;
  for (let index = 0; index < source.length; index += 1) {
    hash = Math.imul(hash ^ source.charCodeAt(index), 16777619);
  }
  return hash >>> 0;
}

export function localizeItemProseJa(item: WardogsItem): ItemProse {
  if (!Object.hasOwn(authored, item.slug)) throw new Error(`Missing ja item prose: ${item.slug}`);
  if (sourceSignature(item) !== sourceSignatures[item.slug]) throw new Error(`Stale ja item prose: ${item.slug}`);
  return {...authored[item.slug], unconfirmedFacts: authored[item.slug].unconfirmedFacts, confirmedFacts: item.confirmedFacts?.map(translateFact)};
}
